import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const iconsDir = join(root, "packages", "ui", "src", "wallets", "icons");
const generatedFile = join(root, "packages", "ui", "src", "wallets", "icons.generated.ts");
const localIconOverrides = {
  bitget: join(root, "icon", "bitget.svg"),
  guarda: join(root, "icon", "guarda.svg"),
  walletconnect: join(root, "icon", "walletconnect.svg")
};
const adapterGeneratedFiles = {
  tronlink: {
    file: join(root, "packages", "adapters", "tronlink", "src", "icon.generated.ts"),
    exportName: "TRONLINK_ICON"
  },
  walletconnect: {
    file: join(root, "packages", "adapters", "walletconnect", "src", "icon.generated.ts"),
    exportName: "WALLETCONNECT_ICON"
  }
};
const sourceBaseUrl = "https://walletadapter.org/wallets";

const iconSources = [
  ["walletconnect", "WalletConnect.svg"],
  ["tronlink", "TronLink.svg"],
  ["metamask", "MetaMask.svg"],
  ["okx", "okx.svg"],
  ["bitget", "Bitget.svg"],
  ["binance", "Binance.svg"],
  ["tokenpocket", "TokenPocket.svg"],
  ["trust", "Trust.svg"],
  ["gate", "GateWallet.svg"],
  ["foxwallet", "Fox.svg"],
  ["bybit", "Bybit.svg"],
  ["imtoken", "imToken.svg"],
  ["tomo", "Tomo.svg"],
  ["guarda", "Guarda.svg"],
  ["backpack", "Backpack.svg"],
  ["onekey", "OneKey.svg"],
  ["ledger", "Ledger.svg"]
];

await mkdir(iconsDir, { recursive: true });

const walletIcons = {};
const failures = [];

for (const [id, filename] of iconSources) {
  const url = `${sourceBaseUrl}/${filename}`;
  try {
    const overrideFile = localIconOverrides[id];
    const svgSource = overrideFile ? await readFile(overrideFile, "utf8").catch(() => undefined) : undefined;
    const responseText = svgSource ?? (await fetchSvg(url));
    const svg = normalizeSvg(responseText);
    if (!svg.includes("<svg")) throw new Error("response is not an SVG");
    await writeFile(join(iconsDir, `${id}.svg`), svg);
    walletIcons[id] = `data:image/svg+xml,${encodeURIComponent(svg)}`;
    console.log(`${svgSource ? "copied" : "fetched"} ${id} from ${svgSource ? overrideFile : url}`);
  } catch (error) {
    failures.push(`${id} (${url}): ${error instanceof Error ? error.message : String(error)}`);
    console.warn(`skipped ${id}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

await writeFile(
  generatedFile,
  `// Generated by scripts/fetch-wallet-icons.mjs. Do not edit manually.\n` +
    `export const walletIcons: Record<string, string> = ${JSON.stringify(walletIcons, null, 2)};\n`
);

for (const [id, config] of Object.entries(adapterGeneratedFiles)) {
  const icon = walletIcons[id];
  if (!icon) continue;
  await writeFile(
    config.file,
    `// Generated by scripts/fetch-wallet-icons.mjs. Do not edit manually.\n` +
      `export const ${config.exportName} = ${JSON.stringify(icon)};\n`
  );
}

if (failures.length > 0) {
  console.warn(`Generated icon map with ${failures.length} skipped icons:\n- ${failures.join("\n- ")}`);
}

function normalizeSvg(svg) {
  return svg.replace(/\r\n/g, "\n").trim();
}

async function fetchSvg(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return response.text();
}
