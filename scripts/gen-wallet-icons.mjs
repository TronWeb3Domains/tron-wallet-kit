import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const iconsDir = join(root, "packages", "client", "src", "wallets", "icons");
const generatedFile = join(root, "packages", "client", "src", "wallets", "icons.generated.ts");

const icons = {};
const mimeTypes = {
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".webp": "image/webp"
};
const files = (await readdir(iconsDir, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && Boolean(mimeTypes[extname(entry.name).toLowerCase()]))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b));

for (const file of files) {
  const extension = extname(file).toLowerCase();
  const id = file.slice(0, -extension.length);
  const mimeType = mimeTypes[extension];
  if (extension === ".svg") {
    const svg = normalizeSvg(await readFile(join(iconsDir, file), "utf8"));
    if (!svg.includes("<svg")) throw new Error(`${file} is not an SVG`);
    icons[id] = `data:${mimeType};base64,${Buffer.from(svg, "utf8").toString("base64")}`;
    continue;
  }
  icons[id] = `data:${mimeType};base64,${(await readFile(join(iconsDir, file))).toString("base64")}`;
}

const sourcePath = relative(dirname(generatedFile), iconsDir).replace(/\\/g, "/");
await writeFile(
  generatedFile,
  `// Generated by scripts/gen-wallet-icons.mjs from ${sourcePath}/*.{svg,png,webp}. Do not edit manually.\n` +
    `export const WALLET_ICONS: Record<string, string> = ${JSON.stringify(icons, null, 2)};\n\n` +
    `export const walletIcons = WALLET_ICONS;\n\n` +
    `export function getWalletIcon(walletId: string): string | undefined {\n` +
    `  return WALLET_ICONS[walletId];\n` +
    `}\n`
);

console.log(`Generated ${Object.keys(icons).length} wallet icons at ${relative(root, generatedFile).replace(/\\/g, "/")}`);

function normalizeSvg(svg) {
  return svg.replace(/\r\n/g, "\n").trim();
}
